// 知识库上传的整体上限。路由文件不能导出普通变量(Next 只认 HTTP 方法等),单独放这里,测试也能调小。

export const UPLOAD_LIMITS = {
  /** 一次最多几个文件 */
  maxFiles: 20,
  /** 整个请求体最大字节数:边读边数,超了立刻停止读取 */
  maxRequestBytes: 100 * 1024 * 1024,
  /**
   * 一次上传从开始处理到返回的总时长。常见网关 / 反向代理 60 秒就断开:超过它,用户看到失败,
   * 服务端却还在解析、入库。用完了剩下的文件标为未处理,不解析不入库
   */
  budgetMs: 55_000,
  /**
   * 每个进程同时处理的上传请求数。每个请求最多在内存里缓冲 maxRequestBytes:
   * 超过就在读请求体之前直接拒绝(503),内存最多约 maxInflight × maxRequestBytes
   */
  maxInflight: 4,
};
